#!/usr/bin/env bash
# Rebuild ForestShell's gnome-shell.css = stock GNOME dark base + Forest Glass layer,
# validate it, swap it in atomically, live-reload the user theme, and revert
# automatically if GNOME Shell logs stylesheet errors.
#
# Idempotent: the output is generated from scratch each run, never appended to.
# The stock base is re-extracted from the installed GNOME Shell, so rerunning
# after a GNOME update picks up the new upstream stylesheet.
#
# Usage: build-shell-theme.sh [--no-reload] [--dry-run]
set -euo pipefail
source "$HOME/.config/forest-glass/bin/fg-lib.sh"

THEME_DIR="$HOME/.local/share/themes/ForestShell/gnome-shell"
OUT="$THEME_DIR/gnome-shell.css"
LAYER="$FG_HOME/src/forest-glass-shell.css"
GRES=/usr/share/gnome-shell/gnome-shell-theme.gresource
RELOAD=1; DRY=0
for a in "$@"; do
  case "$a" in --no-reload) RELOAD=0 ;; --dry-run) DRY=1 ;; *) echo "unknown arg $a" >&2; exit 2 ;; esac
done

tmp="$(mktemp "$THEME_DIR/.gnome-shell.css.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

{
  printf '/* GENERATED by ~/.config/forest-glass/bin/build-shell-theme.sh — do not edit.\n'
  printf '   Base: stock %s dark stylesheet. Layer: %s */\n' "$(gnome-shell --version)" "${LAYER/#$HOME/\~}"
  gresource extract "$GRES" /org/gnome/shell/theme/gnome-shell-dark.css
  printf '\n\n'
  cat "$LAYER"
} > "$tmp"

python3 -I "$FG_HOME/bin/validate-st-css.py" "$tmp" >/dev/null || {
  python3 -I "$FG_HOME/bin/validate-st-css.py" "$tmp"; echo "validation failed; live theme untouched" >&2; exit 1; }

if cmp -s "$tmp" "$OUT"; then fg_log "gnome-shell.css already up to date"; exit 0; fi
if [ "$DRY" = 1 ]; then diff -u "$OUT" "$tmp" | diffstat 2>/dev/null || diff -u "$OUT" "$tmp" | tail -n +1 | wc -l; exit 0; fi

fg_track_file A "$OUT"
chmod --reference="$OUT" "$tmp" 2>/dev/null || chmod 644 "$tmp"
mv -f "$tmp" "$OUT"; trap - EXIT
fg_mark_file "$OUT"
fg_log "wrote $OUT ($(wc -l < "$OUT") lines)"

[ "$RELOAD" = 1 ] || exit 0
"$FG_HOME/bin/reload-shell-theme.sh" || {
  echo "reload reported stylesheet errors — restoring previous theme" >&2
  fg_revert_file "$OUT"; "$FG_HOME/bin/reload-shell-theme.sh" || true; exit 1; }
